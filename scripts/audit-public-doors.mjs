#!/usr/bin/env node
/**
 * One door per public symbol.
 *
 * A package's `exports` map is its public surface, and a name reachable from two subpaths is a name
 * a reader has to check twice to learn whether the two are the same thing. They always were here —
 * every duplicate found was an aggregate published alongside the granular files it re-exported — but
 * the adapters had split themselves across the aliases, so three of them imported the same symbol by
 * three different paths and no reader could tell that was accidental.
 *
 * Types count. A type alias reachable from two subpaths misleads exactly as much as a function does,
 * and is what a `.d.ts`-only entry publishes, so the check runs through the checker rather than
 * through `import()`.
 *
 * The same pass answers a second question the other surface gates cannot: **does every import in
 * this repository still resolve?** A subpath that leaves the `exports` map takes no type with it, so
 * the type-surface snapshot reports nothing; the widget catalogue is untouched, so the contract
 * differ reports `patch`. The place that breaks first is a demo, and demos are built by the e2e
 * chain rather than by `npm run test`. Reading the imports is cheaper than building them and finds
 * the same thing.
 */
import { readFileSync, existsSync, readdirSync, statSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import ts from "typescript";

const ROOT = resolve(new URL("..", import.meta.url).pathname);
/**
 * Every package that publishes, read from the workspace rather than listed.
 *
 * The check exists because a removal reached a demo unnoticed, and a demo does not care which
 * package the name came from — so the roster cannot be the two that publish a contract, nor the four
 * somebody happened to write down. A package left out of a list like this is not declared safe, it
 * is simply never asked; and adding a package to the workspace would silently be the way to stay
 * out. `@modyra/angular` is the exception and it is named as one: its manifest is generated by
 * ng-packagr into a build directory, so there is no source manifest here to read a surface from.
 */
const PACKAGES = readdirSync(resolve(new URL("..", import.meta.url).pathname, "packages"))
  .filter((name) => {
    const manifest = resolve(new URL("..", import.meta.url).pathname, `packages/${name}/package.json`);
    if (!existsSync(manifest)) return false;
    return JSON.parse(readFileSync(manifest, "utf8")).private !== true;
  });

let failures = 0;
/** Names reachable from more than one subpath — counted apart, because each finding here has its
 *  own repair and one closing sentence for all three sent a reader looking for the wrong thing. */
let ambiguous = 0;
/**
 * A package whose root entry deliberately re-exports its granular subpaths, with the reason and the
 * count on the day it was recorded.
 *
 * Recorded rather than repaired here, because the repair is a **breaking change to a published
 * surface** and that belongs to the package's owner. Recorded rather than excluded, because an
 * exclusion is silence: this prints every run, cannot grow, and fails the moment it stops being
 * true — which is what should happen when somebody finally picks which subpath keeps a name.
 *
 * `@modyra/lit` was outside this audit's roster entirely until the roster became the workspace, so
 * nobody had been told. Every one of its public names is reachable from `.` and from one of
 * `./adapter` or `./ui`.
 */
const AGGREGATES = {
  lit: {
    names: 276,
    reason: "its root entry re-exports ./adapter and ./ui whole; choosing which door keeps each "
      + "name removes a published subpath, so it is the package owner's decision",
  },
};
/** Ambiguity a declaration accounts for, per package, so the two can be compared rather than summed. */
const accounted = new Map();
/** Per package: name → the subpaths that publish it. */
const published = new Map();
for (const pkg of PACKAGES) {
  const manifest = JSON.parse(readFileSync(resolve(ROOT, `packages/${pkg}/package.json`), "utf8"));
  const entries = [];
  // A stylesheet entry is a door with nothing to name: it must resolve, and there is no symbol to
  // publish twice. Recorded so an import of one is checked rather than skipped.
  const assets = [];
  for (const [subpath, target] of Object.entries(manifest.exports ?? {})) {
    const js = typeof target === "string" ? target : (target.import ?? target.default ?? "");
    if (!String(js).endsWith(".js")) {
      if (String(js)) assets.push(subpath);
      continue;
    }
    const declaration = resolve(ROOT, `packages/${pkg}`, String(js).replace(/\.js$/, ".d.ts"));
    if (existsSync(declaration)) entries.push([subpath, declaration]);
  }
  if (entries.length === 0 && assets.length === 0) continue;

  const program = ts.createProgram(entries.map(([, file]) => file), { allowJs: false });
  const checker = program.getTypeChecker();
  const doors = new Map();
  for (const [subpath, file] of entries) {
    const source = program.getSourceFile(file);
    if (!source) continue;
    const symbol = checker.getSymbolAtLocation(source);
    if (!symbol) continue;
    for (const exported of checker.getExportsOfModule(symbol)) {
      const name = exported.getName();
      if (!doors.has(name)) doors.set(name, []);
      doors.get(name).push(subpath);
    }
  }

  for (const subpath of assets) {
    if (!doors.has(subpath)) doors.set(subpath, []);
    doors.get(subpath).push(subpath);
  }
  published.set(pkg, doors);

  const multi = [...doors].filter(([, subpaths]) => subpaths.length > 1);
  console.log(
    `@modyra/${pkg}: ${entries.length + assets.length} subpaths, ${doors.size} public names, ${multi.length} reachable from more than one`,
  );
  const aggregate = AGGREGATES[pkg];
  if (aggregate) {
    accounted.set(pkg, multi.length);
    console.log(`  declared aggregate: ${aggregate.reason}`);
    // Named rather than listed: 276 identical lines say one thing 276 times and bury everything
    // else in this report. The number is the ratchet; the names are one command away.
    if (multi.length > aggregate.names) {
      console.log(`  DEFECT: ${multi.length} names now, ${aggregate.names} when this was recorded — `
        + "the aggregate grew, which a declaration may not do");
      ambiguous += multi.length - aggregate.names;
    }
    if (multi.length < aggregate.names) {
      // Failing in this direction too, for the same reason a closed cycle still recorded fails: a
      // number that no longer describes the code is a claim, and a ratchet whose claim drifts stops
      // being able to say anything about the next change.
      console.log(`  DEFECT: ${aggregate.names - multi.length} fewer than recorded — re-record, `
        + "a ratchet that has drifted no longer holds anything");
      ambiguous += aggregate.names - multi.length;
    }
    continue;
  }
  for (const [name, subpaths] of multi) {
    console.log(`  ${name}  ←  ${subpaths.join(", ")}`);
    ambiguous += 1;
  }
}

/**
 * Every import of a package published from this workspace, checked against what the
 * package publishes — the subpath and the names alike.
 *
 * Sources only. A compiled `dist` mirrors its source and a changelog describes a surface that has
 * since moved on; both would report a break that does not exist.
 */
const ROOTS = ["packages", "examples", "apps", "e2e", "scripts", "site/src", "docs"];
const SKIP = new Set(["node_modules", "dist", ".astro", "test-results", "contract-baseline"]);
const SOURCE = /\.(ts|tsx|mts|mjs|js|jsx|svelte|vue)$/;
// Built from the roster above rather than spelled again: two lists of the same packages in one file
// disagree the day one of them is edited, and the half that is not edited goes quiet.
const IMPORT = new RegExp(
  `(?:import|export)\\s+(?:type\\s+)?(?:\\{([^}]*)\\}|\\*\\s+as\\s+\\w+|\\w+)?\\s*(?:from\\s*)?`
  + `["']@modyra/(${PACKAGES.join("|")})(/[^"']+)?["']`,
  "g",
);

const unresolved = [];
const walk = (dir) => {
  for (const entry of readdirSync(dir)) {
    if (SKIP.has(entry)) continue;
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) { walk(path); continue; }
    if (!SOURCE.test(entry)) continue;
    // Comments removed: this repository writes import examples in doc blocks, and an example is not
    // an import — judging one reports a demo as broken for a line nothing executes.
    const text = readFileSync(path, "utf8")
      .replace(/\/\*[\s\S]*?\*\//g, " ")
      .replace(/^\s*\/\/.*$/gm, " ");
    for (const match of text.matchAll(IMPORT)) {
      const [, names, pkg, tail] = match;
      const doors = published.get(pkg);
      if (!doors) continue;
      const subpath = tail ? `.${tail}` : ".";
      const declared = new Set([...doors.values()].flat());
      if (!declared.has(subpath)) {
        unresolved.push([relative(ROOT, path), `@modyra/${pkg}${tail ?? ""} is not a declared subpath`]);
        continue;
      }
      for (const raw of (names ?? "").split(",")) {
        const name = raw.trim().replace(/^type\s+/, "").split(/\s+as\s+/)[0].trim();
        if (!name) continue;
        if (!doors.get(name)?.includes(subpath)) {
          unresolved.push([relative(ROOT, path), `${name} is not published by @modyra/${pkg}${tail ?? ""}`]);
        }
      }
    }
  }
};
for (const root of ROOTS) if (existsSync(resolve(ROOT, root))) walk(resolve(ROOT, root));

if (unresolved.length > 0) {
  console.log(`\n${unresolved.length} import(s) name something the package does not publish:`);
  for (const [file, what] of unresolved) console.log(`  ${file}: ${what}`);
  failures += unresolved.length;
} else {
  console.log(`Every ${PACKAGES.map((p) => `@modyra/${p}`).join(", ")} import in the repository resolves.`);
}

/**
 * The third question, and the one the other two cannot ask: **is anything behind no door at all?**
 *
 * A field controller is what a renderer adopts to stop deciding a kind's behaviour for itself, and
 * the adoption audit counts how many have been. Three of them were written, tested and never
 * exported: their types were published, so a consumer could name the interface and had no way to
 * build one, and the adoption bench reported "none offered" — correctly, because from the public
 * door nothing was.
 *
 * Nothing said so. The duplicate-door check above guards the opposite problem, the type surface only
 * compares what is exported, and their own specs reach them by deep path into `dist/`, which is the
 * house habit and therefore not a signal.
 *
 * Narrow on purpose: only `create*FieldController`. A helper exported for a sibling module to use is
 * an ordinary internal, but a field controller exists to be adopted, and one that cannot be reached
 * is a promise the package does not keep.
 */
const controllerDoors = published.get("widgets") ?? new Map();
const unreachable = [];
const fieldDir = resolve(ROOT, "packages/widgets/src/field");
if (existsSync(fieldDir)) {
  for (const file of readdirSync(fieldDir)) {
    if (!file.endsWith("-controller.ts")) continue;
    const source = readFileSync(join(fieldDir, file), "utf8");
    for (const [, name] of source.matchAll(/export function (create\w*FieldController)\b/g)) {
      if (!controllerDoors.has(name)) unreachable.push([`packages/widgets/src/field/${file}`, name]);
    }
  }
}
if (unreachable.length > 0) {
  console.log(`\n${unreachable.length} field controller(s) written and published by no door:`);
  for (const [file, name] of unreachable) console.log(`  ${file}: ${name} is not exported by @modyra/widgets`);
  console.log(
    "\nA renderer cannot adopt what it cannot import, and the adoption bench will report the kind as\n" +
      "offering nothing — which is true, and says nothing about the controller sitting behind it.",
  );
  failures += unreachable.length;
}

// Three questions, three repairs. One sentence for all of them sent a reader looking for a second
// door when the finding was that there was none, or for a missing export when an import had simply
// been renamed.
if (unreachable.length > 0) {
  console.log("\nPUBLISHED BY NO DOOR — export the controller from the package barrel, or delete it.");
}
if (unresolved.length > 0) {
  console.log("\nIMPORT NAMES NOTHING — the subpath resolves and the name it asks for is not there.");
}
if (ambiguous > 0) {
  console.log(
    "\nPUBLIC DOORS AMBIGUOUS — publish each name from one subpath. An aggregate that re-exports a\n" +
      "granular subpath means one of the two is redundant; keep whichever names a domain.",
  );
}
// A declaration for a package that has stopped being ambiguous is a claim about the code that is no
// longer true, and leaving it would excuse an ambiguity that came back later under the same name.
const stale = Object.keys(AGGREGATES).filter((pkg) => (accounted.get(pkg) ?? 0) === 0);
for (const pkg of stale) {
  console.log(`\nDEFECT: @modyra/${pkg} is declared an aggregate and publishes nothing twice — prune it`);
}
if (failures + ambiguous + stale.length > 0) process.exit(1);
console.log(`PUBLIC DOORS UNAMBIGUOUS — ${PACKAGES.length} package(s) asked, `
  + `${Object.keys(AGGREGATES).length} declared aggregate(s)`);
